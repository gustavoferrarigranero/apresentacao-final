export type Status = 'active' | 'inactive';
export interface Resource<T> {
    data: T;
    message?: string;
}
export interface Page<T> {
    data: T[];
    links: {
        first: string;
        last: string;
        prev: string | null;
        next: string | null;
    };
    meta: {
        current_page: number;
        last_page: number;
        per_page: number;
        total: number;
        from: number | null;
        to: number | null;
    };
}
